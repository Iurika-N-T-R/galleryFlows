/** French is the source; "Utiliser la langue anglaise" swaps in [EN]. [args] fill the %s / %d of the template. */
fun t(fr: String, vararg args: Any?): String {
    val s = if (Prefs.english) EN[fr] ?: fr else fr
    return if (args.isEmpty()) s else s.format(*args)
}

